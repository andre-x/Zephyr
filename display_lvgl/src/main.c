const lv_image_dsc_t Kite = {
  .header.cf = LV_COLOR_FORMAT_I1,
  .header.w = 80,
  .header.h = 47,
  .header.stride = 10,
  .data_size = sizeof(Kite_map),
  .data = Kite_map,
};

int main(void)
{
    const struct device *display_dev;
    lv_obj_t *version_label;
    lv_obj_t *img;
    
    /* Variables for blinking logic */
    static uint32_t blink_counter = 0;
    static bool show_colon = true;

    display_dev = DEVICE_DT_GET(DT_CHOSEN(zephyr_display));
    if (!device_is_ready(display_dev)) return 0;

    img = lv_image_create(lv_screen_active());
    lv_image_set_src(img, &Kite);
    lv_obj_align(img, LV_ALIGN_CENTER, 0, -8);

    version_label = lv_label_create(lv_screen_active());
    lv_obj_set_style_text_font(version_label, &lv_font_unscii_8, 0);
    lv_obj_set_style_text_color(version_label, lv_color_black(), 0);
    lv_obj_align(version_label, LV_ALIGN_CENTER, 0, 24);

    /* Initial text set */
    lv_label_set_text_fmt(version_label, "Zephyr: %s", KERNEL_VERSION_STRING);

    lv_timer_handler();
    display_blanking_off(display_dev);

    /* Hardware Fix for Black Background */
    const struct device *i2c_bus = DEVICE_DT_GET(DT_NODELABEL(i2c0));
    if (device_is_ready(i2c_bus)) {
        uint8_t cmd[] = {0x00, 0xA7}; 
        i2c_write(i2c_bus, cmd, sizeof(cmd), 0x3c);
    }

    while (1) {
        /* Every 10 iterations (10 * 100ms = 1s), toggle the colon */
        if (blink_counter >= 10) {
            if (show_colon) {
                lv_label_set_text_fmt(version_label, "Zephyr: %s", KERNEL_VERSION_STRING);
            } else {
                /* Use a space instead of a colon to prevent text from shifting */
                lv_label_set_text_fmt(version_label, "Zephyr  %s", KERNEL_VERSION_STRING);
            }
            show_colon = !show_colon;
            blink_counter = 0;
        }

        lv_timer_handler();
        k_sleep(K_MSEC(100));
        blink_counter++;
    }
}